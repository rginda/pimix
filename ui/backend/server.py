# Precompute 72 logarithmically spaced frequency bands from 20 Hz to 20,000 Hz for the RTA
NUM_SPEC_BINS = 72
FFT_SIZE = 4096
FFT_WINDOW = np.hanning(FFT_SIZE).astype(np.float32)
# Normalize window coherent gain so a 0 dBFS sine wave reads 0.0 dBFS on the RTA
WINDOW_NORM = float(np.sum(FFT_WINDOW) * 0.5)
FFT_FREQS = np.fft.rfftfreq(FFT_SIZE, d=1.0 / SAMPLE_RATE)
SPEC_BAND_EDGES = np.logspace(np.log10(20.0), np.log10(20000.0), NUM_SPEC_BINS + 1)
SPEC_CENTER_FREQS = [
    round(float(math.sqrt(SPEC_BAND_EDGES[i] * SPEC_BAND_EDGES[i + 1])), 1)
    for i in range(NUM_SPEC_BINS)
]

# Precompute bin index slices for each of the 72 log bands
SPEC_BIN_MAP = []
for i in range(NUM_SPEC_BINS):
    f_lo, f_hi = SPEC_BAND_EDGES[i], SPEC_BAND_EDGES[i + 1]
    idxs = np.where((FFT_FREQS >= f_lo) & (FFT_FREQS <= f_hi))[0]
    if len(idxs) == 0:
        nearest = int(np.argmin(np.abs(FFT_FREQS - math.sqrt(f_lo * f_hi))))
        SPEC_BIN_MAP.append(slice(nearest, nearest + 1))
    else:
        SPEC_BIN_MAP.append(slice(int(idxs[0]), int(idxs[-1]) + 1))


