class PiMixController:
    def __init__(self):
        self.state = copy.deepcopy(DEFAULT_STATE)
        self.camilla = CamillaWsClient()
        self.ws_clients: set[asyncio.StreamWriter] = set()
        self.test_procs: list[subprocess.Popen] = []
        self.test_mode: str = "stopped"
        # Rolling 4096-frame stereo mono-summed buffers for USB1, USB2, and Master
        self.ring_usb1 = np.zeros(FFT_SIZE, dtype=np.float32)
        self.ring_usb2 = np.zeros(FFT_SIZE, dtype=np.float32)
        self.latest_spectrum = {
            "usb1": [-95.0] * NUM_SPEC_BINS,
            "usb2": [-95.0] * NUM_SPEC_BINS,
            "master": [-95.0] * NUM_SPEC_BINS,
        }
        self.load_state()

    def load_state(self):
        if STATE_FILE.exists():
            try:
                loaded = json.loads(STATE_FILE.read_text())
                if "channels" in loaded and "master" in loaded:
                    self.state = loaded
            except Exception as e:
                print(f"Warning: could not load {STATE_FILE}: {e}")

