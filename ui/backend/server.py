def build_camilladsp_config(state: dict, capture_channels: int = 4) -> dict:
    filters = {}
    pipeline = []

    any_solo = any(ch.get("solo", False) for ch in state["channels"])

    # 1. Per-channel EQ filters for active hardware channels
    for ch in state["channels"]:
        pair = ch.get("hw_ch_pair")
        if not pair or max(pair) >= capture_channels:
            continue
        cid = ch["id"]
        if not ch.get("eq_bypass", False):
            band_names = []
            for idx, b in enumerate(ch.get("eq_bands", [])):
                if not b.get("enabled", True):
                    continue
                fname = f"{cid}_eq_{idx}"
                btype = b.get("type", "Peaking")
                freq = float(max(20.0, min(20000.0, b.get("freq", 1000.0))))
                gain = float(max(-24.0, min(24.0, b.get("gain", 0.0))))
                q = float(max(0.2, min(12.0, b.get("q", 1.0))))
                filters[fname] = {
                    "type": "Biquad",
                    "parameters": {
                        "type": btype,
                        "freq": freq,
                        "gain": gain,
                        "q": q,
                    },
                }
                band_names.append(fname)
            if band_names:
                pipeline.append({
                    "type": "Filter",
                    "channels": list(pair),
                    "names": band_names,
                })

    # 2. Summing Mixer (maps capture channels -> 2 stereo output channels)
    left_sources = []
    right_sources = []

    for ch in state["channels"]:
        pair = ch.get("hw_ch_pair")
        if not pair or max(pair) >= capture_channels:
            continue

        is_muted = bool(ch.get("mute", False))
        if any_solo and not ch.get("solo", False):
            is_muted = True

        gain_db = float(ch.get("gain_db", 0.0))
        if gain_db <= -59.5:
            is_muted = True

        pan = float(max(-1.0, min(1.0, ch.get("pan", 0.0))))
        left_pan_db = 0.0 if pan <= 0.0 else (20.0 * math.log10(max(1e-4, 1.0 - pan)))
        right_pan_db = 0.0 if pan >= 0.0 else (20.0 * math.log10(max(1e-4, 1.0 + pan)))

        l_gain = max(-70.0, min(18.0, gain_db + left_pan_db))
        r_gain = max(-70.0, min(18.0, gain_db + right_pan_db))
        inv = bool(ch.get("invert", False))

        left_sources.append({
            "channel": pair[0],
            "gain": round(l_gain, 2),
            "inverted": inv,
            "mute": is_muted,
        })
        right_sources.append({
            "channel": pair[1],
            "gain": round(r_gain, 2),
            "inverted": inv,
            "mute": is_muted,
        })

    if not left_sources:
        left_sources.append({"channel": 0, "gain": -60.0, "inverted": False, "mute": True})
    if not right_sources:
        right_sources.append({"channel": 1, "gain": -60.0, "inverted": False, "mute": True})

    mixers = {
        "pimix_matrix": {
            "description": "PiMix Stereo Summing Matrix",
            "channels": {"in": capture_channels, "out": 2},
            "mapping": [
                {"dest": 0, "sources": left_sources},
                {"dest": 1, "sources": right_sources},
            ],
        }
    }
    pipeline.append({"type": "Mixer", "name": "pimix_matrix"})

    # 3. Master 10-Band EQ + Master Gain + Soft Limiter
    master = state["master"]
    master_filter_names = []

    if not master.get("eq_bypass", False):
        for idx, b in enumerate(master.get("eq_bands", [])):
            if not b.get("enabled", True):
                continue
            fname = f"master_eq_{idx}"
            btype = b.get("type", "Peaking")
            freq = float(max(20.0, min(20000.0, b.get("freq", 1000.0))))
            gain = float(max(-24.0, min(24.0, b.get("gain", 0.0))))
            q = float(max(0.2, min(12.0, b.get("q", 1.414))))
            filters[fname] = {
                "type": "Biquad",
                "parameters": {
                    "type": btype,
                    "freq": freq,
                    "gain": gain,
                    "q": q,
                },
            }
            master_filter_names.append(fname)

    m_gain = float(max(-60.0, min(12.0, master.get("gain_db", 0.0))))
    m_mute = bool(master.get("mute", False)) or (m_gain <= -59.5)
    filters["master_trim"] = {
        "type": "Gain",
        "parameters": {
            "gain": round(m_gain, 2),
            "inverted": False,
            "mute": m_mute,
        },
    }
    master_filter_names.append("master_trim")

    if master.get("limiter_enabled", True):
        filters["master_limiter"] = {
            "type": "Limiter",
            "parameters": {
                "clip_limit": -0.5,
                "soft_clip": True,
            },
        }
        master_filter_names.append("master_limiter")

    if master_filter_names:
        pipeline.append({
            "type": "Filter",
            "channels": [0, 1],
            "names": master_filter_names,
        })

    cfg = {
        "devices": {
            "samplerate": SAMPLE_RATE,
            "chunksize": 512,
            "queuelimit": 4,
            "enable_rate_adjust": True,
            "adjust_period": 3,
            "target_level": 1024,
            "capture": {
                "type": "Alsa",
                "channels": capture_channels,
                "device": "pimix_snoop",
                "format": "S32LE",
            },
            "playback": {
                "type": "Alsa",
                "channels": 2,
                "device": "hw:Device,0",
                "format": "S16LE",
            },
        },
        "filters": filters,
        "mixers": mixers,
        "pipeline": pipeline,
    }
    return cfg


