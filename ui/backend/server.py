WS_MAGIC = "258EAFA5-E914-47DA-95CA-C5AB0DC85B11"


async def ws_read_frame(reader: asyncio.StreamReader):
    hdr = await reader.readexactly(2)
    b0, b1 = hdr[0], hdr[1]
    opcode = b0 & 0x0F
    masked = bool(b1 & 0x80)
    length = b1 & 0x7F
    if length == 126:
        length = struct.unpack("!H", await reader.readexactly(2))[0]
    elif length == 127:
        length = struct.unpack("!Q", await reader.readexactly(8))[0]
    mask_key = await reader.readexactly(4) if masked else None
    payload = bytearray(await reader.readexactly(length))
    if masked and mask_key:
        for i in range(length):
            payload[i] ^= mask_key[i & 3]
    return opcode, bytes(payload)


def ws_encode_frame(payload: bytes, opcode: int = 1, mask: bool = False) -> bytes:
    out = bytearray()
    out.append(0x80 | (opcode & 0x0F))
    length = len(payload)
    mask_bit = 0x80 if mask else 0x00
    if length < 126:
        out.append(mask_bit | length)
    elif length < 65536:
        out.append(mask_bit | 126)
        out.extend(struct.pack("!H", length))
    else:
        out.append(mask_bit | 127)
        out.extend(struct.pack("!Q", length))
    if mask:
        mkey = b"\x37\xfa\x21\x3d"
        out.extend(mkey)
        masked_bytes = bytearray(payload)
        for i in range(length):
            masked_bytes[i] ^= mkey[i & 3]
        out.extend(masked_bytes)
    else:
        out.extend(payload)
    return bytes(out)


class CamillaWsClient:
    """Async WebSocket client for CamillaDSP v3.0.0 on 127.0.0.1:1234."""

    def __init__(self, host="127.0.0.1", port=CAMILLA_PORT):
        self.host = host
        self.port = port
        self.reader = None
        self.writer = None
        self.lock = asyncio.Lock()

    async def connect(self):
        if self.writer is not None:
            return True
        try:
            reader, writer = await asyncio.wait_for(
                asyncio.open_connection(self.host, self.port), timeout=1.5
            )
            key = base64.b64encode(os.urandom(16)).decode("ascii")
            req = (
                f"GET / HTTP/1.1\r\n"
                f"Host: {self.host}:{self.port}\r\n"
                f"Upgrade: websocket\r\n"
                f"Connection: Upgrade\r\n"
                f"Sec-WebSocket-Key: {key}\r\n"
                f"Sec-WebSocket-Version: 13\r\n\r\n"
            )
            writer.write(req.encode("ascii"))
            await writer.drain()
            while True:
                line = await asyncio.wait_for(reader.readline(), timeout=1.5)
                if line in (b"\r\n", b"\n", b""):
                    break
            self.reader = reader
            self.writer = writer
            return True
        except Exception:
            await self.close()
            return False

    async def close(self):
        if self.writer:
            try:
                self.writer.close()
                await self.writer.wait_closed()
            except Exception:
                pass
        self.reader = None
        self.writer = None

    async def command(self, cmd_obj):
        async with self.lock:
            if not await self.connect():
                return None
            try:
                raw = json.dumps(cmd_obj).encode("utf-8")
                self.writer.write(ws_encode_frame(raw, opcode=1, mask=True))
                await self.writer.drain()
                while True:
                    opcode, data = await asyncio.wait_for(ws_read_frame(self.reader), timeout=1.5)
                    if opcode == 1:
                        return json.loads(data.decode("utf-8"))
                    elif opcode == 8:
                        await self.close()
                        return None
                    elif opcode == 9:
                        self.writer.write(ws_encode_frame(data, opcode=10, mask=True))
                        await self.writer.drain()
            except Exception:
                await self.close()
                return None


