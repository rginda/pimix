def compute_log_spectrum_db(samples_norm: np.ndarray) -> list[float]:
    """Compute 72-band log spectrum (20 Hz - 20 kHz) in dBFS from a 4096-sample float32 buffer."""
    if len(samples_norm) < FFT_SIZE:
        return [-95.0] * NUM_SPEC_BINS
    windowed = samples_norm * FFT_WINDOW
    mag = np.abs(np.fft.rfft(windowed)) / WINDOW_NORM
    out = []
    for sl in SPEC_BIN_MAP:
        peak_mag = float(np.max(mag[sl]))
        db = 20.0 * math.log10(max(1e-5, peak_mag))
        out.append(round(max(-95.0, min(6.0, db)), 1))
    return out


